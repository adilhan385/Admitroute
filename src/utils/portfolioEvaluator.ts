import type { UserProfile, PortfolioAudit } from '../types';

/**
 * Реалистичный оценщик портфолио и внеучебных активностей.
 * Строго соблюдает баланс: распознает реальные достижения (наука, проекты, олимпиады)
 * и дает честную обратную связь по верификации для топовых зарубежных вузов.
 */
export function evaluatePortfolio(profile: UserProfile): PortfolioAudit {
  const text = (profile.portfolioText || '').trim().toLowerCase();

  // If no portfolio text provided
  if (!text || text.length < 10) {
    return {
      rating: 'basic',
      scoreOutOf100: 20,
      abroadCompetitiveness: 'Недостаточная без усиления',
      strongPoints: [
        'Фокус на академических показателях (GPA и вступительные экзамены)'
      ],
      criticalGaps: [
        'Полное отсутствие подтвержденных внеучебных достижений (Extracurriculars)',
        'Для топовых зарубежных вузов (США, Европа, Азия) холистическая оценка составляет до 40% решения',
        'Нет подтверждения лидерских качеств или проектного опыта'
      ],
      honestVerdict: 'Профиль держится исключительно на академических оценках. Для большинства вузов Казахстана этого достаточно (где решает ЕНТ), но для топовых зарубежных программ и грантов шансы крайне низкие без 2–3 сильных проектов или олимпиадных достижений.',
      recommendedNextActivities: [
        'Создать 1 завершенный прикладной проект по специальности (веб-сервис, исследование или прототип)',
        'Принять участие в региональном хакатоне или предметной олимпиаде',
        'Набрать минимум 30–40 часов подтвержденной волонтерской деятельности'
      ]
    };
  }

  // 1. Science, Research & Biomedical Inventions (Наука, исследования, медицина, открытия)
  const hasScience = /учен|научн|исследован|лаборатор|патент|открыти|изобре|препарат|лекарств|леарств|вакцин|био|онколог|рак|бешенств|болезн|вирус|медицин|фарм|генетик|синтез|хими|физик|астроном|нано/i.test(text);

  // 2. Applied Projects & Engineering (Проекты, разработка, IT, изобретения)
  const hasProjects = /проект|github|приложени|бот|сайт|разработ|стартап|стать|публикаци|придумал|создал|изобрел|сконструир|написал|моделирован|прототип|робот|электроник|алгоритм|нейросеть/i.test(text);

  // 3. Olympiads & Academic Competitions (Олимпиады и академические турниры)
  const hasOlympiad = /олимпиад|медал|призер|победител|республиканск|международн|ioi|imo|ibo|ichyo|жаутыков|isef|дарын|шаги в будущее|научных соревнов|лауреат|диплом|грамота/i.test(text);

  // 4. Hackathons & Case Championships (Хакатоны и соревнования)
  const hasHackathon = /хакатон|hackathon|чемпионат|конкурс|турнир|ctf|кейс|соревнован/i.test(text);

  // 5. Leadership & Community Organizing (Лидерство и организаторский опыт)
  const hasLeadership = /капитан|президент|основа|организова|руководил|команд|клуб|дебат|старост|ментор|лидер|сооснователь/i.test(text);

  // 6. Volunteering & Social Impact (Волонтерство и общественная польза)
  const hasVolunteering = /волонтер|благотворительн|помощь|экологи|социальн|фонд|активист|донор|эко/i.test(text);

  // 7. Sports, Arts & Creative fields (Спорт, искусство, публикации)
  const hasCreativeOrSport = /спорт|кмс|мастер спорта|разряд|музык|инструмент|худ|выставк|театр|писател|книга|публикац|чемпион/i.test(text);

  // Verification indicators (наличие документальных подтверждений)
  const hasVerification = /патент|стать|публикац|журнал|scopus|pubmed|isef|дарын|диплом|сертификат|лаборатор|ссылк|github|демо|научный руководитель|рецензи/i.test(text);

  const strongPoints: string[] = [];
  const criticalGaps: string[] = [];
  let score = 30;

  if (hasScience) {
    strongPoints.push('Научно-исследовательская деятельность: прикладные разработки и естественнонаучные/медицинские исследования');
    score += 30;
  }

  if (hasProjects) {
    strongPoints.push('Практический проектный опыт: создание авторских решений, прототипов или прикладных систем');
    score += 20;
  }

  if (hasOlympiad) {
    strongPoints.push('Олимпиадный опыт и участие в независимых академических соревнованиях');
    score += 25;
  }

  if (hasHackathon) {
    strongPoints.push('Опыт работы в командных хакатонах, кейс-чемпионатах и технических турнирах');
    score += 15;
  }

  if (hasLeadership) {
    strongPoints.push('Лидерский потенциал и подтвержденные организаторские инициативы');
    score += 10;
  }

  if (hasVolunteering) {
    strongPoints.push('Социальная ответственность и подтвержденная волонтерская деятельность');
    score += 10;
  }

  if (hasCreativeOrSport) {
    strongPoints.push('Достижения в спорте, искусстве или авторском творчестве');
    score += 10;
  }

  if (hasVerification) {
    strongPoints.push('Наличие верифицируемой базы: публикации, патенты, ссылки или официальные дипломы');
    score += 10;
  }

  // Realistic critical gaps detection
  if (hasScience && !hasVerification) {
    criticalGaps.push('Масштабные научные открытия требуют строгой верификации: публикации в рецензируемых журналах (Scopus/PubMed), патенты или призовые места на научных конкурсах (Regeneron ISEF, Дарын). Без документов комиссия расценит проект как неподтвержденную гипотезу.');
  }

  if (!hasScience && !hasOlympiad && !hasHackathon) {
    criticalGaps.push('Нет побед на независимых внешних соревнованиях (городских, республиканских олимпиадах или хакатонах)');
  }

  if (!hasProjects && !hasScience) {
    criticalGaps.push('Отсутствует осязаемый проектный результат (код, ссылка, действующий прототип или опубликованная работа)');
  }

  if (!hasLeadership) {
    criticalGaps.push('Не отражена лидерская инициатива (роль создателя, капитана или организатора сообщества)');
  }

  if (!hasVolunteering && profile.targetRegion === 'usa') {
    criticalGaps.push('Для американских вузов критически важна социальная отдача (Community Service / волонтерство)');
  }

  if (criticalGaps.length === 0) {
    criticalGaps.push('Высокая международная конкуренция: для топ-вузов (Ivy League, Оксфорд) потребуется подчеркнуть масштаб измеримого импакта');
  }

  // Cap score realistically
  const finalScore = Math.min(90, Math.max(30, score));

  let rating: 'strong' | 'moderate' | 'basic' = 'moderate';
  let abroadCompetitiveness: 'Высокая' | 'Умеренная' | 'Недостаточная без усиления' = 'Умеренная';
  let honestVerdict = '';

  if (finalScore >= 65) {
    rating = 'strong';
    abroadCompetitiveness = 'Высокая';
    if (hasScience) {
      honestVerdict = 'Заявлен выдающийся научно-исследовательский потенциал в сфере прикладных инноваций (Tier-1 Extracurricular для топ-вузов США, Европы и NU). Разработка медицинских или исследовательских решений ценится приемными комиссиями максимально высоко. Главная задача — подкрепить проект публикацией, патентной заявкой или отзывом научного руководителя лаборатории.';
    } else {
      honestVerdict = 'У вас сильное, сбалансированное портфолио выше среднего уровня абитуриентов. Вы конкурентоспособны на грантовые программы в Европе и Азии, но для топ-20 вузов США потребуется четко упаковать измеримый импакт каждого достижения.';
    }
  } else if (finalScore >= 45) {
    rating = 'moderate';
    abroadCompetitiveness = 'Умеренная';
    honestVerdict = 'Портфолио имеет хороший старт и практическую направленность. Приемная комиссия увидит интерес к специальности, но для победы в жестких грантовых конкурсах (с покрытием 100%) потребуется подкрепить активность 1 независимой наградой или официальным проектом.';
  } else {
    rating = 'basic';
    abroadCompetitiveness = 'Недостаточная без усиления';
    honestVerdict = 'Базовый уровень внеучебной активности. Текущих записей недостаточно для победы в холистическом конкурсе на престижные зарубежные стипендии. Сделайте упор на государственные гранты (где ключевую роль играют экзамены) либо срочно подготовьте 1–2 подтвержденных проекта.';
  }

  const recommendedNextActivities: string[] = [];
  if (hasScience) {
    recommendedNextActivities.push('Оформить заявку на патент на изобретение или опубликовать препринт статьи в научном издании');
    recommendedNextActivities.push('Подать исследование на международную научную выставку (Regeneron ISEF, Genius Olympiad) или конкурс Дарын');
    recommendedNextActivities.push('Запросить рекомендательное письмо от профессора / доктора наук с описанием вашего вклада в разработку');
  } else {
    recommendedNextActivities.push('Упаковать 1 ключевой проект в понятное портфолио с демонстрацией (демо-ссылка, видео 60 сек, GitHub)');
    recommendedNextActivities.push('Собрать подтверждающие сертификаты, рекомендации от наставников и дипломы за последние 2 года');
    recommendedNextActivities.push('Описать активности через формулу «Сделал X с помощью Y, что привело к измеримому результату Z»');
  }

  return {
    rating,
    scoreOutOf100: finalScore,
    abroadCompetitiveness,
    strongPoints,
    criticalGaps,
    honestVerdict,
    recommendedNextActivities
  };
}
